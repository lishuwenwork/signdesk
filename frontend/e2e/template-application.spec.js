import { test, expect, authenticatedContext } from './fixtures.js'

const created = new Set()
test.afterEach(async ({ playwright }) => {
  const cleanup = await authenticatedContext(playwright)
  try {
    for (const id of created) {
      expect((await cleanup.delete(`/api/platforms/${id}`, { data: {} })).ok()).toBe(true)
      created.delete(id)
    }
  } finally { await cleanup.dispose() }
})
async function post(request, path, data) {
  const response = await request.post(path, { data })
  expect(response.ok()).toBe(true)
  return response.json()
}
async function saved(request, platformId, id) {
  const tree = await (await request.get('/api/platforms')).json()
  return tree.find(platform => platform.id === platformId).accounts.flatMap(account => account.requests).find(row => row.id === id)
}
async function selectPlatform(page, name) {
  await expect(page.locator('.platform-workspace')).toBeVisible()
  const picker = page.getByRole('combobox', { name: '选择平台', exact: true })
  if (await picker.isVisible()) {
    await picker.press('ArrowDown')
    await page.getByRole('option', { name, exact: true }).click()
  } else await page.locator('.platform-choice').filter({ hasText: name }).click()
}
async function selectTarget(dialog, id) {
  const row = dialog.locator(`.apply-target[data-request-id="${id}"]`)
  await row.locator('.el-checkbox').click()
  await expect(row.getByRole('checkbox')).toBeChecked()
}
async function confirmation(page, accepted = true) {
  await page.locator('.el-message-box').getByRole('button', { name: accepted ? '确认' : '取消', exact: true }).click()
}
async function setup(request, name) {
  const platform = await post(request, '/api/platforms', { name, enabled: true })
  created.add(platform.id)
  const first = await post(request, `/api/platforms/${platform.id}/accounts`, { alias: '账号 A', enabled: true })
  const second = await post(request, `/api/platforms/${platform.id}/accounts`, { alias: '账号 B', enabled: true })
  const curl = `curl 'http://127.0.0.1:18081/check?template-application=${platform.id}' -H 'Cookie: template-apply-fixture=own-account'`
  const one = await post(request, `/api/accounts/${first.id}/requests`, { name: '保留原名 A', enabled: true, curl })
  const two = await post(request, `/api/accounts/${second.id}/requests`, { name: '禁用请求 B', enabled: false, curl })
  const untouched = await post(request, `/api/accounts/${first.id}/requests`, { name: '不选择的请求', enabled: true, curl })
  const template = await post(request, `/api/platforms/${platform.id}/templates`, { name: '批量签到模板' })
  return { platform, first, one, two, untouched, template, curl }
}

for (const width of [1440, 390]) {
  test(`manual selection creates associations and one-click linked application preserves request configuration at ${width}px`, async ({ page, request }, info) => {
    test.setTimeout(120000)
    const name = `模板批量应用平台-${width}`
    const { platform, first, one, two, untouched, template, curl } = await setup(request, name)
    const receivedBefore = (await (await request.get('http://127.0.0.1:18081/received')).json()).length
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    await page.goto('/#/platforms')
    await selectPlatform(page, name)
    await page.getByRole('button', { name: '接口模板', exact: true }).click()
    const templates = page.getByRole('dialog', { name: '接口模板', exact: true })
    const card = templates.locator(`.template-card[data-template-id="${template.id}"]`)
    await card.getByRole('button', { name: '编辑', exact: true }).click()
    const editor = page.getByRole('dialog', { name: '编辑接口模板', exact: true })
    await editor.getByRole('textbox', { name: '成功等于值', exact: true }).fill('99')
    await editor.locator('.failure-option .el-switch').click()
    await editor.getByRole('button', { name: '保存模板', exact: true }).click()
    await expect(card).toContainText('已关联 0 个请求')
    expect((await saved(request, platform.id, one.id)).rules.success.value).toBe(0)
    await card.getByRole('button', { name: '选择请求应用', exact: true }).click()
    const manual = page.getByRole('dialog', { name: '选择请求并应用模板', exact: true })
    await expect(manual.locator('.apply-target')).toHaveCount(3)
    await selectTarget(manual, one.id)
    await manual.getByRole('textbox', { name: '筛选模板应用请求', exact: true }).fill('账号 B')
    await selectTarget(manual, two.id)
    await manual.getByRole('textbox', { name: '筛选模板应用请求', exact: true }).fill('')
    await expect(manual).toContainText('已选 2 / 3')
    await expect(manual).toContainText('已禁用，应用不会启用')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1)
    await page.screenshot({ path: info.outputPath(`template-select-${width}.png`), fullPage: true })
    await manual.getByRole('button', { name: '取消', exact: true }).click()
    await expect(manual).not.toBeVisible()
    expect((await saved(request, platform.id, one.id)).templateId).toBeNull()
    await card.getByRole('button', { name: '选择请求应用', exact: true }).click()
    await expect(manual.locator('.apply-target')).toHaveCount(3)
    await selectTarget(manual, one.id)
    await selectTarget(manual, two.id)
    await manual.getByRole('button', { name: '应用并关联所选请求', exact: true }).click()
    await expect(page.locator('.el-message-box')).toHaveCount(0)
    await expect(manual).not.toBeVisible()
    await expect(card).toContainText('已关联 2 个请求')
    const applied = await saved(request, platform.id, one.id)
    expect(applied).toMatchObject({ templateId: template.id, name: '保留原名 A', enabled: 1, currentRevision: 1, authPaused: 0, todayState: 'none' })
    expect(applied.rules).toMatchObject({ success: { value: 99 }, failureOnSuccessMismatch: true })
    expect(await saved(request, platform.id, two.id)).toMatchObject({ templateId: template.id, enabled: 0, name: '禁用请求 B' })
    expect(await saved(request, platform.id, untouched.id)).toMatchObject({ templateId: null, rules: { success: { value: 0 } } })
    expect((await (await request.get(`/api/requests/${one.id}/revision`)).json()).rawCurl).toBe(curl)
    await card.getByRole('button', { name: '编辑', exact: true }).click()
    await editor.getByRole('textbox', { name: '成功等于值', exact: true }).fill('0')
    await editor.getByRole('button', { name: '保存模板', exact: true }).click()
    expect((await saved(request, platform.id, one.id)).rules.success.value).toBe(99)
    await card.getByRole('button', { name: '应用到已关联请求', exact: true }).click()
    const linked = page.getByRole('dialog', { name: '应用到已关联请求', exact: true })
    await expect(linked.locator('.apply-target')).toHaveCount(2)
    await expect(linked.getByRole('checkbox')).toHaveCount(0)
    await expect(linked).not.toContainText('不选择的请求')
    await linked.getByRole('button', { name: '确认更新已关联请求', exact: true }).click()
    await expect(page.locator('.el-message-box')).toHaveCount(0)
    await expect(linked).not.toBeVisible()
    expect((await saved(request, platform.id, one.id)).rules.success.value).toBe(0)
    expect((await saved(request, platform.id, two.id)).enabled).toBe(0)
    await templates.getByRole('button', { name: '关闭', exact: true }).click()
    await page.getByRole('region', { name: '账号 账号 A', exact: true }).getByRole('button', { name: '添加请求', exact: true }).click()
    const newDialog = page.getByRole('dialog', { name: '导入完整 cURL', exact: true })
    await newDialog.getByRole('combobox', { name: '接口模板（可选）', exact: true }).press('ArrowDown')
    await page.getByRole('option', { name: '批量签到模板', exact: true }).click()
    await newDialog.getByRole('textbox', { name: '请求名称', exact: true }).fill('新建时自动关联')
    await newDialog.getByRole('textbox', { name: '完整 cURL', exact: true }).fill(curl)
    await newDialog.getByRole('button', { name: '解析预览', exact: true }).click()
    await newDialog.getByRole('button', { name: '设置结果规则', exact: true }).click()
    await expect(newDialog.getByRole('switch', { name: '反向失败判断', exact: true })).toHaveAttribute('aria-checked', 'true')
    const creation = page.waitForResponse(response => new URL(response.url()).pathname === `/api/accounts/${first.id}/requests` && response.request().method() === 'POST')
    await newDialog.getByRole('button', { name: '保存请求', exact: true }).click()
    const added = await (await creation).json()
    await expect(newDialog).not.toBeVisible()
    expect((await saved(request, platform.id, added.id)).templateId).toBe(template.id)
    const row = page.locator(`.request-row[data-request-id="${one.id}"]`)
    await row.getByRole('button', { name: '保留原名 A', exact: true }).click()
    const detail = page.getByRole('dialog', { name: '保留原名 A', exact: true })
    await detail.getByRole('button', { name: '结果规则', exact: true }).click()
    await expect(detail).toContainText('已关联接口模板')
    await expect(detail.locator('.rule-block')).toHaveCount(4)
    await detail.getByRole('button', { name: '关闭', exact: true }).click()
    await page.getByRole('heading', { name: '平台与账号', exact: true }).click()
    await row.getByRole('button', { name: '保留原名 A的更多操作', exact: true }).click()
    await page.getByRole('menuitem', { name: '编辑名称 / 规则', exact: true }).click()
    const requestEditor = page.getByRole('dialog', { name: '编辑名称与结果规则', exact: true })
    await requestEditor.getByText('解除模板关联（保留当前规则）', { exact: true }).click()
    await expect(requestEditor.getByRole('checkbox', { name: '解除模板关联（保留当前规则）', exact: true })).toBeChecked()
    await requestEditor.getByRole('button', { name: '保存请求', exact: true }).click()
    await expect.poll(async () => (await saved(request, platform.id, one.id)).templateId).toBeNull()
    expect((await saved(request, platform.id, one.id)).rules).toEqual({ ...applied.rules, success: { ...applied.rules.success, value: 0 } })
    await page.getByRole('button', { name: '接口模板', exact: true }).click()
    await expect(card).toContainText('已关联 2 个请求')
    await card.getByRole('button', { name: '删除', exact: true }).click()
    await confirmation(page)
    await expect(card).toHaveCount(0)
    expect((await saved(request, platform.id, two.id)).templateId).toBeNull()
    expect((await saved(request, platform.id, added.id)).templateId).toBeNull()
    expect((await saved(request, platform.id, two.id)).rules.success.value).toBe(0)
    expect((await (await request.get('http://127.0.0.1:18081/received')).json()).length).toBe(receivedBefore)
  })
}

test('a stale application preview rolls back the whole selection and can be refreshed explicitly', async ({ page, request }) => {
  const { platform, one, two, template } = await setup(request, '模板应用版本冲突')
  await page.goto('/#/platforms')
  await selectPlatform(page, '模板应用版本冲突')
  await page.getByRole('button', { name: '接口模板', exact: true }).click()
  const templates = page.getByRole('dialog', { name: '接口模板', exact: true })
  await templates.locator(`.template-card[data-template-id="${template.id}"]`).getByRole('button', { name: '选择请求应用', exact: true }).click()
  const manual = page.getByRole('dialog', { name: '选择请求并应用模板', exact: true })
  await selectTarget(manual, one.id)
  await selectTarget(manual, two.id)
  const current = await saved(request, platform.id, one.id)
  const updated = await request.put(`/api/requests/${one.id}`, { data: { name: current.name, enabled: true, version: current.version, rules: { success: { path: 'code', value: 99 } } } })
  expect(updated.ok()).toBe(true)
  await manual.getByRole('button', { name: '应用并关联所选请求', exact: true }).click()
  await expect(page.locator('.el-message-box')).toHaveCount(0)
  await expect(manual).toContainText('本次没有覆盖任何请求')
  expect((await saved(request, platform.id, one.id)).rules.success.value).toBe(99)
  expect((await saved(request, platform.id, two.id)).templateId).toBeNull()
  expect((await saved(request, platform.id, two.id)).version).toBe(1)
  await manual.getByRole('button', { name: '重新加载范围', exact: true }).click()
  await expect(manual).toContainText('已选 2 / 3')
  await manual.getByRole('button', { name: '应用并关联所选请求', exact: true }).click()
  await expect(page.locator('.el-message-box')).toHaveCount(0)
  await expect(manual).not.toBeVisible()
  expect((await saved(request, platform.id, two.id)).templateId).toBe(template.id)
})
